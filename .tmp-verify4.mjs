import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 430, height: 931 }, deviceScaleFactor: 2 });
const wait = (ms) => page.waitForTimeout(ms);
await page.goto('http://localhost:5173', { waitUntil: 'networkidle' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await wait(1300);
await page.getByText('위로 밀어 잠금 해제').click();
await wait(800);
const state = () => page.evaluate(() => {
  const win = [...document.querySelectorAll('[data-app-window]')].pop();
  return { app: win?.getAttribute('data-app-window') ?? null, pe: win ? getComputedStyle(win).pointerEvents : null, notif: !!document.querySelector('button[aria-label="알림 모두 지우기"]') };
});
await page.getByRole('button', { name: '설정', exact: true }).first().click();
await wait(700);
await page.mouse.click(215, 30);
await wait(600);
console.log('notif', JSON.stringify(await state()));
await page.getByRole('button', { name: '홈으로' }).click();
await wait(600);
console.log('after home bar 1', JSON.stringify(await state()));
const before = await page.evaluate(() => document.documentElement.className);
await page.locator('[data-app-window] button[role="switch"]').first().click({ timeout: 2000 }).catch(() => {});
await wait(400);
console.log('toggle worked', before !== (await page.evaluate(() => document.documentElement.className)));
await page.getByRole('button', { name: '홈으로' }).click();
await wait(600);
console.log('after home bar 2', JSON.stringify(await state()));
await browser.close();
